// Converts an exported question-bank workbook into SQL for Supabase.
//
//   node tools/import-sheet.js path/to/QuestionBank.xlsx   (writes supabase/seed.sql)
//
// Each sheet (tab) becomes a module; each row becomes a question.
// Expected columns, same as the old app: A question, B-E options A-D, F correct letter (A-D).
// A header row is skipped automatically. Re-running the generated SQL ADDS rows again,
// so run it once (or clear the tables first).
const XLSX = require("xlsx");
const fs = require("fs");
const path = require("path");

const input = process.argv[2];
if (!input) {
  console.error("Usage: node tools/import-sheet.js <file.xlsx|file.csv>");
  process.exit(1);
}

const sql = (v) => `'${String(v).replace(/'/g, "''")}'`;
const wb = XLSX.readFile(input);
const out = [
  "-- Generated by tools/import-sheet.js. Run once in the Supabase SQL editor.",
  "begin;",
];
const warnings = [];
let totalQuestions = 0;

wb.SheetNames.forEach((name, moduleIndex) => {
  const rows = XLSX.utils
    // blankrows kept so warning row numbers match the spreadsheet; blanks are skipped below.
    .sheet_to_json(wb.Sheets[name], { header: 1, defval: "", blankrows: true })
    .map((r) => r.map((c) => String(c).trim()));

  const valid = [];
  rows.forEach((r, i) => {
    const [rawPrompt, a, b, c, d, correct] = r;
    // Drop manual numbering such as "Q12. " or "3. " (the app shows its own order).
    const prompt = (rawPrompt || "").replace(/^\s*Q?\d+[.)]\s+/i, "");
    const letter = (correct || "").toUpperCase();
    if (i === 0 && !["A", "B", "C", "D"].includes(letter)) return; // header row
    if (!prompt) return;
    if (!a || !b || !c || !d || !["A", "B", "C", "D"].includes(letter)) {
      warnings.push(`Sheet "${name}" row ${i + 1}: skipped (missing option or correct answer not A-D)`);
      return;
    }
    valid.push({ prompt, a, b, c, d, letter });
  });

  if (valid.length === 0) {
    warnings.push(`Sheet "${name}": no valid questions, module not created`);
    return;
  }

  const values = valid
    .map(
      (q, i) =>
        `((select id from m), ${sql(q.prompt)}, ${sql(q.a)}, ${sql(q.b)}, ${sql(q.c)}, ${sql(q.d)}, ${sql(q.letter)}, ${i})`
    )
    .join(",\n  ");

  out.push(
    `\n-- Module: ${name} (${valid.length} questions)`,
    `with m as (\n  insert into public.modules (title, position) values (${sql(name)}, ${moduleIndex}) returning id\n)`,
    `insert into public.questions (module_id, prompt, option_a, option_b, option_c, option_d, correct_option, position)\nvalues\n  ${values};`
  );
  totalQuestions += valid.length;
  console.log(`${name}: ${valid.length} questions`);
});

out.push("\ncommit;\n");
const target = path.join(__dirname, "..", "supabase", "seed.sql");
fs.writeFileSync(target, out.join("\n"));
console.log(`\nWrote ${target} (${totalQuestions} questions)`);
// Summarise skipped rows per sheet instead of printing thousands of lines.
const bySheet = {};
warnings.forEach((w) => {
  const m = w.match(/^Sheet "(.*?)" row (\d+): (.*)$/);
  if (!m) return console.warn("WARNING:", w);
  (bySheet[m[1]] = bySheet[m[1]] || { rows: [], why: m[3] }).rows.push(Number(m[2]));
});
Object.entries(bySheet).forEach(([s, { rows, why }]) =>
  console.warn(`WARNING: "${s}": ${rows.length} rows skipped (${why}); first rows: ${rows.slice(0, 8).join(", ")}`)
);
